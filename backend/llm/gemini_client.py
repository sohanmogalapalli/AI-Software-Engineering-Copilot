import json
from typing import Generator, Optional
import httpx
from backend.utils.config import settings
from backend.utils.logging import logger

DEFAULT_GEMINI_MODEL = "gemini-3-flash-preview"

GEMINI_MODEL_ALIASES = {
    "gemini-2.0-flash": "gemini-3-flash-preview",
    "gemini-1.5-flash": "gemini-3-flash-preview",
    "gemini-2.5-flash": "gemini-3-flash-preview",
    "gemini-3.8-flash": "gemini-3-flash-preview",
    "gemini-flash": "gemini-3-flash-preview",
    "gemini-flash-latest": "gemini-3-flash-preview",
    "gemini-flash-lite": "gemini-3.1-flash-lite-preview",
    "gemini-pro": "gemini-3.1-pro-preview",
}

class GeminiClient:
    def __init__(self, api_key: Optional[str] = None, default_model: Optional[str] = None):
        self.api_key = api_key or settings.GEMINI_API_KEY
        self.default_model = default_model or DEFAULT_GEMINI_MODEL
        self.base_url = "https://generativelanguage.googleapis.com/v1beta/models"

    def _get_api_key(self, api_key_override: Optional[str] = None) -> str:
        key = api_key_override or self.api_key or settings.GEMINI_API_KEY
        if not key:
            raise ValueError(
                "Google Gemini API key is missing. Please configure your GEMINI_API_KEY in the settings menu or .env file."
            )
        return key

    def _resolve_model(self, model: Optional[str]) -> str:
        target = model or self.default_model or DEFAULT_GEMINI_MODEL
        return GEMINI_MODEL_ALIASES.get(target, target)

    def _build_payload(self, prompt: str, system: Optional[str] = None, temperature: float = 0.2, max_tokens: int = 1500) -> dict:
        payload = {
            "contents": [
                {
                    "role": "user",
                    "parts": [{"text": prompt}]
                }
            ],
            "generationConfig": {
                "temperature": temperature,
                "maxOutputTokens": max_tokens
            }
        }
        if system:
            payload["systemInstruction"] = {
                "parts": [{"text": system}]
            }
        return payload

    def generate(
        self,
        prompt: str,
        system: Optional[str] = None,
        temperature: float = 0.2,
        max_tokens: int = 1500,
        model: Optional[str] = None,
        api_key: Optional[str] = None
    ) -> str:
        key = self._get_api_key(api_key)
        target_model = self._resolve_model(model)
        url = f"{self.base_url}/{target_model}:generateContent?key={key}"
        payload = self._build_payload(prompt, system, temperature, max_tokens)

        with httpx.Client(timeout=60.0) as client:
            resp = client.post(url, json=payload)
            if resp.status_code == 404 and target_model != DEFAULT_GEMINI_MODEL:
                logger.warning(f"Model {target_model} returned 404, falling back to {DEFAULT_GEMINI_MODEL}")
                target_model = DEFAULT_GEMINI_MODEL
                url = f"{self.base_url}/{target_model}:generateContent?key={key}"
                resp = client.post(url, json=payload)

            if resp.status_code != 200:
                try:
                    err = resp.json().get("error", {}).get("message", resp.text)
                except Exception:
                    err = resp.text
                logger.error(f"Gemini API error ({resp.status_code}): {err}")
                raise RuntimeError(f"Gemini API error ({resp.status_code}): {err}")

            data = resp.json()
            candidates = data.get("candidates", [])
            if not candidates:
                return "No response generated by Gemini."
            parts = candidates[0].get("content", {}).get("parts", [])
            return "".join(p.get("text", "") for p in parts)

    def _stream_from_url(self, client: httpx.Client, url: str, payload: dict) -> Generator[str, None, None]:
        with client.stream("POST", url, json=payload) as response:
            if response.status_code == 404:
                raise FileNotFoundError("Model not found (404)")

            if response.status_code != 200:
                content = response.read().decode("utf-8", errors="replace")
                try:
                    err_msg = json.loads(content).get("error", {}).get("message", content)
                except Exception:
                    err_msg = content
                yield f"\n[Google Gemini API error ({response.status_code}): {err_msg}]"
                return

            for line in response.iter_lines():
                if not line:
                    continue
                if line.startswith("data: "):
                    data_str = line[6:].strip()
                    if data_str == "[DONE]":
                        break
                    try:
                        chunk = json.loads(data_str)
                        candidates = chunk.get("candidates", [])
                        if candidates:
                            parts = candidates[0].get("content", {}).get("parts", [])
                            for p in parts:
                                if "text" in p:
                                    yield p["text"]
                    except json.JSONDecodeError:
                        pass

    def stream_generate(
        self,
        prompt: str,
        system: Optional[str] = None,
        temperature: float = 0.2,
        max_tokens: int = 1500,
        model: Optional[str] = None,
        api_key: Optional[str] = None
    ) -> Generator[str, None, None]:
        try:
            key = self._get_api_key(api_key)
        except Exception as e:
            yield f"\n[Configuration Error: {e}]"
            return

        target_model = self._resolve_model(model)
        url = f"{self.base_url}/{target_model}:streamGenerateContent?alt=sse&key={key}"
        payload = self._build_payload(prompt, system, temperature, max_tokens)

        try:
            with httpx.Client(timeout=60.0) as client:
                try:
                    yield from self._stream_from_url(client, url, payload)
                except FileNotFoundError:
                    # Model returned 404, fallback to DEFAULT_GEMINI_MODEL
                    logger.warning(f"Gemini model {target_model} returned 404, falling back to {DEFAULT_GEMINI_MODEL}")
                    fallback_url = f"{self.base_url}/{DEFAULT_GEMINI_MODEL}:streamGenerateContent?alt=sse&key={key}"
                    yield from self._stream_from_url(client, fallback_url, payload)
        except Exception as e:
            logger.error(f"Streaming error with Gemini: {e}")
            yield f"\n[Gemini streaming error: {e}]"
